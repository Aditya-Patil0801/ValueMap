import jsPDF from "jspdf";
import { useState } from "react";
import {
  LineChart,
  Line,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  ResponsiveContainer,
} from "recharts";

interface ValuationHistory {
  value: number;
  valuationDate: string;
  notes?: string;
}

interface Property {
  _id: string;
  propertyName: string;
  address: string;
  city: string;
  district?: string;
  state: string;

  location: {
    type: "Point";
    coordinates: [number, number];
  };

  status: "Completed" | "Under Construction" | "Pending";

  valuation: {
    currentValue: number;
    previousValue?: number;
    valuationDate: string;
  };

  valuationHistory?: ValuationHistory[];

  notes?: string;
}

interface PropertyDetailsProps {
  property: Property;
  onClose: () => void;
  onPropertyUpdated: (
    property: Property
  ) => void;
  onPropertyDeleted: (
    propertyId: string
  ) => void;
}

function PropertyDetails({
  property,
  onClose,
  onPropertyUpdated,
  onPropertyDeleted,
}: PropertyDetailsProps) {
  const [formData, setFormData] = useState({
    propertyName: property.propertyName,
    address: property.address,
    city: property.city,
    district: property.district || "",
    state: property.state,
    status: property.status,
    currentValue:
      property.valuation.currentValue.toString(),
    valuationDate:
      property.valuation.valuationDate.split("T")[0],
    notes: property.notes || "",
  });

  const [saving, setSaving] = useState(false);
  const [deleting, setDeleting] = useState(false);
  const [fieldErrors, setFieldErrors] = useState<Record<string, string>>({});

  const valuationHistory = property.valuationHistory || [];

  const chartData = [
    ...valuationHistory.map((item) => ({
      date: item.valuationDate,
      displayDate: new Date(
        item.valuationDate
      ).toLocaleDateString("en-IN"),
      value: item.value,
    })),

    {
      date: property.valuation.valuationDate,
      displayDate: new Date(
        property.valuation.valuationDate
      ).toLocaleDateString("en-IN"),
      value: property.valuation.currentValue,
    },
  ].sort(
    (a, b) =>
      new Date(a.date).getTime() -
      new Date(b.date).getTime()
  );

  const formatValue = (value: number) => {
    return new Intl.NumberFormat("en-IN", {
      style: "currency",
      currency: "INR",
      maximumFractionDigits: 0,
    }).format(value);
  };
  const handleDownloadReport = () => {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();
    const margin = 15;
    const contentWidth = pageWidth - margin * 2;
    const [longitude, latitude] = property.location.coordinates;

    const currentValue = Number(property.valuation.currentValue);
    const previousValue =
      property.valuation.previousValue !== undefined
        ? Number(property.valuation.previousValue)
        : undefined;

    const valuationChange =
      previousValue !== undefined ? currentValue - previousValue : null;

    const percentageChange =
      previousValue !== undefined && previousValue !== 0
        ? ((currentValue - previousValue) / previousValue) * 100
        : null;

    const generatedDate = new Date().toLocaleDateString("en-IN");
    const valuationDate = new Date(
      property.valuation.valuationDate
    ).toLocaleDateString("en-IN");

    const safeText = (value: unknown, fallback = "N/A") => {
      if (value === null || value === undefined || String(value).trim() === "") {
        return fallback;
      }
      return String(value);
    };

    const formatReportValue = (value: number) =>
      new Intl.NumberFormat("en-IN", {
        style: "currency",
        currency: "INR",
        maximumFractionDigits: 0,
      }).format(value);

    const addPageFooter = () => {
      const pageCount = doc.internal.pages.length - 1;

      for (let page = 1; page <= pageCount; page += 1) {
        doc.setPage(page);
        doc.setDrawColor(220, 225, 232);
        doc.line(margin, pageHeight - 15, pageWidth - margin, pageHeight - 15);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(8);
        doc.setTextColor(100, 110, 125);
        doc.text("Generated by ValueMap", margin, pageHeight - 9);
        doc.text(
          `Page ${page} of ${pageCount}`,
          pageWidth - margin,
          pageHeight - 9,
          { align: "right" }
        );
      }
    };

    let y = 20;

    const ensureSpace = (requiredHeight: number) => {
      if (y + requiredHeight > pageHeight - 23) {
        doc.addPage();
        y = 20;
      }
    };

    const drawSectionHeading = (heading: string) => {
      ensureSpace(16);
      y += 5;
      doc.setFillColor(238, 243, 250);
      doc.roundedRect(margin, y - 5, contentWidth, 10, 2, 2, "F");
      doc.setFont("helvetica", "bold");
      doc.setFontSize(11);
      doc.setTextColor(35, 55, 80);
      doc.text(heading, margin + 3, y + 1.5);
      y += 12;
    };

    const drawLabelValue = (label: string, value: string, valueX = 58) => {
      ensureSpace(9);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(75, 85, 99);
      doc.text(label, margin + 2, y);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(30, 41, 59);
      const lines = doc.splitTextToSize(
        value,
        pageWidth - margin - valueX - margin
      );
      doc.text(lines, valueX, y);
      y += Math.max(7, lines.length * 4.5);
    };

    // Report header
    doc.setFillColor(31, 78, 121);
    doc.rect(0, 0, pageWidth, 38, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(20);
    doc.text("ValueMap", margin, 16);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.text("PROPERTY VALUATION REPORT", margin, 25);
    doc.setFontSize(8);
    doc.text(`Report generated: ${generatedDate}`, pageWidth - margin, 15, {
      align: "right",
    });

    y = 48;

    drawSectionHeading("1. Property Information");
    drawLabelValue("Property Name", safeText(property.propertyName));
    drawLabelValue("Address", safeText(property.address));
    drawLabelValue("City", safeText(property.city));
    drawLabelValue("District", safeText(property.district));
    drawLabelValue("State", safeText(property.state));
    drawLabelValue("Status", safeText(property.status));
    drawLabelValue("Latitude", safeText(latitude));
    drawLabelValue("Longitude", safeText(longitude));

    drawSectionHeading("2. Valuation Summary");
    drawLabelValue("Current Valuation", formatReportValue(currentValue));
    drawLabelValue(
      "Previous Valuation",
      previousValue !== undefined
        ? formatReportValue(previousValue)
        : "Not available"
    );
    drawLabelValue(
      "Valuation Change",
      valuationChange !== null
        ? `${valuationChange >= 0 ? "+" : ""}${formatReportValue(valuationChange)}`
        : "Not available"
    );
    drawLabelValue(
      "Percentage Change",
      percentageChange !== null
        ? `${percentageChange >= 0 ? "+" : ""}${percentageChange.toFixed(2)}%`
        : "Not available"
    );
    drawLabelValue("Valuation Date", valuationDate);

    drawSectionHeading("3. Valuation History");
    const historyRows = (property.valuationHistory || [])
      .map((item) => ({
        date: item.valuationDate,
        value: Number(item.value),
        notes: safeText(item.notes, "—"),
      }))
      .filter((item) => Number.isFinite(item.value))
      .sort(
        (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
      );

    if (historyRows.length === 0) {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9);
      doc.setTextColor(75, 85, 99);
      doc.text("No previous valuation history is available.", margin + 2, y);
      y += 8;
    } else {
      const colDate = margin + 2;
      const colValue = margin + 43;
      const colNotes = margin + 91;
      const notesWidth = pageWidth - margin - colNotes - margin;

      const drawTableHeader = () => {
        ensureSpace(12);
        doc.setFillColor(31, 78, 121);
        doc.rect(margin, y - 5, contentWidth, 10, "F");
        doc.setFont("helvetica", "bold");
        doc.setFontSize(8);
        doc.setTextColor(255, 255, 255);
        doc.text("Date", colDate, y + 1);
        doc.text("Valuation", colValue, y + 1);
        doc.text("Notes", colNotes, y + 1);
        y += 9;
      };

      drawTableHeader();

      historyRows.forEach((item, index) => {
        const dateText = new Date(item.date).toLocaleDateString("en-IN");
        const noteLines = doc.splitTextToSize(item.notes, notesWidth);
        const rowHeight = Math.max(8, noteLines.length * 4 + 3);

        if (y + rowHeight > pageHeight - 23) {
          doc.addPage();
          y = 20;
          drawTableHeader();
        }

        if (index % 2 === 0) {
          doc.setFillColor(247, 249, 252);
          doc.rect(margin, y - 4, contentWidth, rowHeight, "F");
        }

        doc.setFont("helvetica", "normal");
        doc.setFontSize(8);
        doc.setTextColor(45, 55, 72);
        doc.text(dateText, colDate, y);
        doc.text(formatReportValue(item.value), colValue, y);
        doc.text(noteLines, colNotes, y);
        y += rowHeight;
      });

      y += 3;
    }

    drawSectionHeading("4. Additional Notes");
    const propertyNotes = safeText(
      property.notes,
      "No additional notes provided."
    );
    const noteLines = doc.splitTextToSize(propertyNotes, contentWidth - 4);

    noteLines.forEach((line: string) => {
      ensureSpace(6);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9);
      doc.setTextColor(45, 55, 72);
      doc.text(line, margin + 2, y);
      y += 5;
    });

    drawSectionHeading("Disclaimer");
    const disclaimer =
      "This report is generated from information stored in ValueMap. Values and property details should be independently verified. This document is not a certified valuation, legal opinion, or independent property appraisal.";
    const disclaimerLines = doc.splitTextToSize(disclaimer, contentWidth - 4);

    disclaimerLines.forEach((line: string) => {
      ensureSpace(6);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(90, 98, 110);
      doc.text(line, margin + 2, y);
      y += 4.5;
    });

    addPageFooter();

    const safeName =
      property.propertyName.trim().replace(/[^a-z0-9_-]/gi, "_") ||
      "property";
    doc.save(`${safeName}_valuation_report.pdf`);
  };

  const handleChange = (
    event:
      | React.ChangeEvent<HTMLInputElement>
      | React.ChangeEvent<HTMLSelectElement>
      | React.ChangeEvent<HTMLTextAreaElement>
  ) => {
    const { name, value } = event.target;

    setFormData((current) => ({
      ...current,
      [name]: value,
    }));

    setFieldErrors((current) => {
      if (!current[name]) return current;
      const updated = { ...current };
      delete updated[name];
      return updated;
    });
  };

  const validateForm = () => {
    const errors: Record<string, string> = {};

    if (!formData.propertyName.trim()) {
      errors.propertyName = "Property name is required.";
    }
    if (!formData.address.trim()) {
      errors.address = "Address is required.";
    }
    if (!formData.city.trim()) {
      errors.city = "City is required.";
    }
    if (!formData.state.trim()) {
      errors.state = "State is required.";
    }

    const value = Number(formData.currentValue);
    if (!formData.currentValue.trim()) {
      errors.currentValue = "Current valuation is required.";
    } else if (!Number.isFinite(value) || value <= 0) {
      errors.currentValue = "Current valuation must be greater than ₹0.";
    }

    if (!formData.valuationDate) {
      errors.valuationDate = "Valuation date is required.";
    } else {
      const selectedDate = new Date(`${formData.valuationDate}T00:00:00`);
      const today = new Date();
      today.setHours(0, 0, 0, 0);
      if (Number.isNaN(selectedDate.getTime())) {
        errors.valuationDate = "Please enter a valid valuation date.";
      } else if (selectedDate > today) {
        errors.valuationDate = "Valuation date cannot be in the future.";
      }
    }

    setFieldErrors(errors);
    return Object.keys(errors).length === 0;
  };

  const handleUpdate = async () => {
    if (!validateForm()) {
      return;
    }

    try {
      setSaving(true);

      const response = await fetch(
        `http://localhost:5000/api/properties/${property._id}`,
        {
          method: "PUT",
          headers: {
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            propertyName: formData.propertyName,
            address: formData.address,
            city: formData.city,
            district: formData.district,
            state: formData.state,

            status: formData.status,

            valuation: {
              currentValue: Number(
                formData.currentValue
              ),
              valuationDate:
                formData.valuationDate,
            },

            notes: formData.notes,
          }),
        }
      );

      const result = await response.json();

      if (!result.success) {
        alert(
          result.message ||
            "Failed to update property."
        );
        return;
      }

      onPropertyUpdated(result.data);

      alert(
        "Property updated successfully."
      );
    } catch (error) {
      console.error(
        "Failed to update property:",
        error
      );

      alert(
        "Failed to update property."
      );
    } finally {
      setSaving(false);
    }
  };

  const handleDelete = async () => {
    const confirmed = window.confirm(
      `Are you sure you want to delete "${property.propertyName}"?`
    );

    if (!confirmed) {
      return;
    }

    try {
      setDeleting(true);

      const response = await fetch(
        `http://localhost:5000/api/properties/${property._id}`,
        {
          method: "DELETE",
        }
      );

      const result = await response.json();

      if (!result.success) {
        alert(
          result.message ||
            "Failed to delete property."
        );
        return;
      }

      onPropertyDeleted(property._id);
      onClose();
    } catch (error) {
      console.error(
        "Failed to delete property:",
        error
      );

      alert(
        "Failed to delete property."
      );
    } finally {
      setDeleting(false);
    }
  };

  const currentValue =
    property.valuation.currentValue;

  const previousValue =
    property.valuation.previousValue;

  const valuationChange =
    previousValue !== undefined
      ? currentValue - previousValue
      : null;

  const valuationChangePercentage =
    previousValue !== undefined &&
    previousValue !== 0
      ? (valuationChange! / previousValue) * 100
      : null;

  return (
    <div className="modal-overlay">
      <div className="property-details-modal">
        <div className="property-details-header">
          <div>
            <p className="subtitle">
              PROPERTY DETAILS
            </p>

            <h2>{property.propertyName}</h2>

            <p>
              {property.address},{" "}
              {property.city},{" "}
              {property.state}
            </p>
            <button
  type="button"
  className="export-button"
  onClick={async () => {
    const [longitude, latitude] =
      property.location.coordinates;

    try {
      await navigator.clipboard.writeText(
        `${latitude}, ${longitude}`
      );
      alert("Coordinates copied successfully!");
    } catch {
      alert(
        `Coordinates: ${latitude}, ${longitude}`
      );
    }
  }}
>
  📍 Copy Coordinates
</button>
          </div>

          <button
            type="button"
            className="close-button"
            onClick={onClose}
          >
            ×
          </button>
        </div>

<button
  type="button"
  className="export-button"
  onClick={async () => {
    const [longitude, latitude] =
      property.location.coordinates;

    const mapsUrl = `https://www.google.com/maps?q=${latitude},${longitude}`;

    try {
      await navigator.clipboard.writeText(mapsUrl);
      alert("Google Maps link copied successfully!");
    } catch {
      window.prompt("Copy this Google Maps link:", mapsUrl);
    }
  }}
>
  📍 Copy Google Maps Link
</button>
        <div className="property-details-content">
          <div className="property-form-grid">
            <div className="form-group">
              <label>
                Property Name
              </label>

              <input
                name="propertyName"
                value={
                  formData.propertyName
                }
                onChange={handleChange}
                required
              />
              {fieldErrors.propertyName && <small className="field-error">{fieldErrors.propertyName}</small>}
            </div>

            <div className="form-group">
              <label>
                Address
              </label>

              <input
                name="address"
                value={formData.address}
                onChange={handleChange}
                required
              />
              {fieldErrors.address && <small className="field-error">{fieldErrors.address}</small>}
            </div>

            <div className="form-group">
              <label>
                City
              </label>

              <input
                name="city"
                value={formData.city}
                onChange={handleChange}
                required
              />
              {fieldErrors.city && <small className="field-error">{fieldErrors.city}</small>}
            </div>

            <div className="form-group">
              <label>
                District
              </label>

              <input
                name="district"
                value={
                  formData.district
                }
                onChange={handleChange}
              />
            </div>

            <div className="form-group">
              <label>
                State
              </label>

              <input
                name="state"
                value={formData.state}
                onChange={handleChange}
                required
              />
              {fieldErrors.state && <small className="field-error">{fieldErrors.state}</small>}
            </div>

            <div className="form-group">
              <label>
                Status
              </label>

              <select
                name="status"
                value={formData.status}
                onChange={handleChange}
              >
                <option value="Completed">
                  Completed
                </option>

                <option value="Under Construction">
                  Under Construction
                </option>

                <option value="Pending">
                  Pending
                </option>
              </select>
            </div>

            <div className="form-group">
              <label>
                Current Valuation
              </label>

              <input
                type="number"
                name="currentValue"
                value={
                  formData.currentValue
                }
                onChange={handleChange}
                min="0.01"
                step="any"
                required
              />
              {fieldErrors.currentValue && <small className="field-error">{fieldErrors.currentValue}</small>}
            </div>

            <div className="form-group">
              <label>
                Valuation Date
              </label>

              <input
                type="date"
                name="valuationDate"
                value={
                  formData.valuationDate
                }
                onChange={handleChange}
                max={new Date().toISOString().split("T")[0]}
                required
              />
              {fieldErrors.valuationDate && <small className="field-error">{fieldErrors.valuationDate}</small>}
            </div>

            <div className="form-group full-width">
              <label>
                Notes
              </label>

              <textarea
                name="notes"
                value={formData.notes}
                onChange={handleChange}
                rows={4}
              />
            </div>
          </div>

          <div className="valuation-analytics">
            <h3>
              Valuation Analytics
            </h3>

            <div className="valuation-analytics-grid">
              <div className="analytics-card">
                <span>
                  Current Value
                </span>

                <strong>
                  {formatValue(
                    currentValue
                  )}
                </strong>
              </div>

              <div className="analytics-card">
                <span>
                  Previous Value
                </span>

                <strong>
                  {previousValue !==
                  undefined
                    ? formatValue(
                        previousValue
                      )
                    : "N/A"}
                </strong>
              </div>

              <div className="analytics-card">
                <span>
                  Change
                </span>

                <strong>
                  {valuationChange !==
                  null
                    ? formatValue(
                        valuationChange
                      )
                    : "N/A"}
                </strong>
              </div>

              <div className="analytics-card">
                <span>
                  Change %
                </span>

                <strong>
                  {valuationChangePercentage !==
                  null
                    ? `${valuationChangePercentage.toFixed(
                        2
                      )}%`
                    : "N/A"}
                </strong>
              </div>
            </div>
          </div>

          {chartData.length > 1 && (
            <div className="valuation-history">
              <h3>
                Valuation Trend
              </h3>

              <div className="valuation-chart">
  <ResponsiveContainer
    width="100%"
    height={280}
    minWidth={0}
    minHeight={280}
  >
    <LineChart
      data={chartData}
      margin={{
        top: 10,
        right: 20,
        left: 20,
        bottom: 10,
      }}
    >
      <CartesianGrid strokeDasharray="3 3" />

      <XAxis
        dataKey="displayDate"
        tick={{ fontSize: 12 }}
      />

      <YAxis
        tick={{ fontSize: 12 }}
        tickFormatter={(value) =>
          `₹${(Number(value) / 100000).toFixed(0)}L`
        }
      />

      <Tooltip
        formatter={(value) =>
          formatValue(Number(value))
        }
      />

      <Line
        type="monotone"
        dataKey="value"
        stroke="#2563eb"
        strokeWidth={3}
        dot={{
          r: 5,
          fill: "#2563eb",
        }}
        activeDot={{
          r: 7,
        }}
      />
    </LineChart>
  </ResponsiveContainer>
</div>
            </div>
          )}

          <div className="valuation-history">
            <h3>
              Valuation History
            </h3>

            {valuationHistory.length ===
            0 ? (
              <p>
                No previous valuation
                history available.
              </p>
            ) : (
              <div className="valuation-history-list">
                {valuationHistory
                  .slice()
                  .reverse()
                  .map(
                    (
                      history,
                      index
                    ) => (
                      <div
                        className="valuation-history-item"
                        key={`${history.valuationDate}-${index}`}
                      >
                        <div>
                          <strong>
                            {formatValue(
                              history.value
                            )}
                          </strong>

                          <span>
                            {new Date(
                              history.valuationDate
                            ).toLocaleDateString(
                              "en-IN"
                            )}
                          </span>
                        </div>

                        {history.notes && (
                          <p>
                            {
                              history.notes
                            }
                          </p>
                        )}
                      </div>
                    )
                  )}
              </div>
            )}
          </div>
        </div>

        <div className="property-details-footer">
          <button
            type="button"
            className="delete-button"
            onClick={handleDelete}
            disabled={deleting}
          >
            {deleting
              ? "Deleting..."
              : "Delete Property"}
          </button>

          <div>
            <button
              type="button"
              className="secondary-button"
              onClick={onClose}
            >
              Cancel
            </button>

            <button
              type="button"
              className="primary-button"
              onClick={handleUpdate}
              disabled={saving}
            >
              {saving
                ? "Saving..."
                : "Save Changes"}
            </button>
            <button
  type="button"
  className="download-report-button"
  onClick={handleDownloadReport}
>
  <span>↓</span> Download Valuation Report (PDF)
</button>
          </div>
        </div>
      </div>
    </div>
  );
}

export default PropertyDetails;